// Builds src/priorData.ts: last season's per-player totals used as the
// projection model's prior early in a season. Re-run once per season:
//   npx tsx scripts/build-prior.ts 2025-26
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const season = process.argv[2] ?? '2025-26';
const BASE = `https://raw.githubusercontent.com/vaastav/Fantasy-Premier-League/master/data/${season}`;

function parseCsv(text: string): Record<string, string>[] {
  const lines = text.trim().split(/\r?\n/);
  const split = (line: string) => {
    const out: string[] = [];
    let cur = '';
    let quoted = false;
    for (const ch of line) {
      if (ch === '"') quoted = !quoted;
      else if (ch === ',' && !quoted) { out.push(cur); cur = ''; }
      else cur += ch;
    }
    out.push(cur);
    return out;
  };
  const header = split(lines[0]!);
  return lines.slice(1).map((line) => {
    const values = split(line);
    return Object.fromEntries(header.map((h, i) => [h, values[i] ?? '']));
  });
}

async function get(path: string) {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: ${res.status}`);
  return parseCsv(await res.text());
}

const [rows, raw] = await Promise.all([get('gws/merged_gw.csv'), get('players_raw.csv')]);
const codeById = new Map(raw.map((r) => [r['id'], Number(r['code'])]));
const num = (r: Record<string, string>, k: string) => Number(r[k]) || 0;

// Group by player and gameweek so doubles count as one week with two fixtures.
const weeks = new Map<string, { code: number; pos: string; rows: Record<string, string>[] }>();
for (const r of rows) {
  const code = codeById.get(r['element']!);
  if (code == null) continue;
  const key = `${code}:${r['GW'] ?? r['round']}`;
  const w = weeks.get(key) ?? { code, pos: r['position']!, rows: [] };
  w.rows.push(r);
  weeks.set(key, w);
}

// [minutes, starts, fixtures, xg, xa, goals, assists, bonus, saves, yellow, defconGames, defconHits]
const totals = new Map<number, number[]>();
for (const w of weeks.values()) {
  const t = totals.get(w.code) ?? new Array(12).fill(0);
  const sum = (k: string) => w.rows.reduce((s, r) => s + num(r, k), 0);
  t[0] += sum('minutes');
  t[1] += sum('starts');
  t[2] += w.rows.length;
  t[3] += sum('expected_goals');
  t[4] += sum('expected_assists');
  t[5] += sum('goals_scored');
  t[6] += sum('assists');
  t[7] += sum('bonus');
  t[8] += sum('saves');
  t[9] += sum('yellow_cards');
  const pos = w.pos === 'GKP' || w.pos === 'GK' ? 'GK' : w.pos;
  if (w.rows.length === 1 && sum('minutes') >= 60 && pos !== 'GK') {
    t[10] += 1;
    if (sum('defensive_contribution') >= (pos === 'DEF' ? 10 : 12)) t[11] += 1;
  }
  totals.set(w.code, t);
}

const round = (x: number) => Math.round(x * 100) / 100;
const entries = [...totals.entries()]
  .filter(([, t]) => t[2]! > 0)
  .sort(([a], [b]) => a - b)
  .map(([code, t]) => `  ${code}: [${t.map(round).join(', ')}],`);

const out = `// Generated by scripts/build-prior.ts from the ${season} season — do not edit.
// code → [minutes, starts, fixtures, xg, xa, goals, assists, bonus, saves, yellow, defconGames, defconHits]
export const PRIOR_SEASON = '${season}';
export const PRIOR_TOTALS: Record<number, number[]> = {
${entries.join('\n')}
};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/priorData.ts');
writeFileSync(target, out);
console.log(`Wrote ${entries.length} players to ${target}`);
